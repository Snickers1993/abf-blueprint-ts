import { test } from "node:test";
import assert from "node:assert/strict";
import { cpSync, mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { validateIrModule } from "@abfc/ir";
import type { IrModule, IrNode, IrUnit } from "@abfc/ir";
import { buildHir, loadProgram, lower } from "../src/index.js";
import type { HirProgram } from "../src/index.js";
import { config, profile } from "./fn-harness.js";

// getWorldSubsystem(Class) and game row-handle literals, against a fake game-module stub shaped like a generated
// world-flag subsystem (as in a hand-made graph in the Mod Editor: HasWorldFlag has exec pins and a hidden WorldContextObject).
const here = fileURLToPath(new URL("./", import.meta.url));
const projectDir = fileURLToPath(new URL("../../test/fixtures/project", import.meta.url));

const GAME_STUB = `// generated by abfc generate 0.1.0 for test; do not edit, never commit
import type { UObject } from "/Script/CoreUObject";
import type { name } from "@abfc/runtime";

/**
 * @bpPath /Script/FakeWorld.FakeFlagRowHandle
 * @bpKind struct
 */
export declare interface FakeFlagRowHandle {
  /**
   * @bpType name
   */
  RowName: name;
}

/**
 * @bpPath /Script/FakeWorld.FakeFlagSubsystem
 * @bpMeta /Script/CoreUObject.Class
 */
export declare class FakeFlagSubsystem extends UObject {
  /**
   * @bpPath /Script/FakeWorld.FakeFlagSubsystem:HasWorldFlag
   * @bpWorldContext
   * @bpParam WorldFlag struct:/Script/FakeWorld.FakeFlagRowHandle
   * @bpOut ReturnValue bool
   */
  HasWorldFlag(WorldFlag: FakeFlagRowHandle): boolean;
  /**
   * @bpPath /Script/FakeWorld.FakeFlagSubsystem:SetWorldFlag
   * @bpParam WorldFlag struct:/Script/FakeWorld.FakeFlagRowHandle
   * @bpParam bState bool
   * @bpParam Context object:/Script/CoreUObject.Object
   */
  SetWorldFlag(WorldFlag: FakeFlagRowHandle, bState: boolean, Context: UObject | null): void;
}

/**
 * @bpPath /Script/FakeWorld.FakeWorldLibrary
 * @bpMeta /Script/CoreUObject.Class
 */
export declare namespace FakeWorldLibrary {
  /**
   * @bpPath /Script/FakeWorld.FakeWorldLibrary:Conv_NameToFakeFlag
   * @bpPure
   * @bpParam Name name
   * @bpOut ReturnValue struct:/Script/FakeWorld.FakeFlagRowHandle
   */
  function Conv_NameToFakeFlag(Name: name): FakeFlagRowHandle;
}
`;

function source(body: string, members = ""): string {
  return `import { blueprint, event, getWorldSubsystem, isValid, nameOf } from "@abfc/runtime";
import type { name } from "@abfc/runtime";
import { Actor } from "/Script/FakeEngine";
import { FakeWorldLibrary, FakeFlagSubsystem } from "/Script/FakeWorld";
import type { FakeFlagRowHandle } from "/Script/FakeWorld";

@blueprint({ path: "/TestMod/Relay/BP_Flags" })
export class BP_Flags extends Actor {
  Seen!: boolean;
  Row!: name;
${members}
  @event
  Go(): void {
${body}
  }
}
`;
}

function hirOf(body: string, members = ""): HirProgram {
  const dir = mkdtempSync(join(here, "subsys-"));
  try {
    cpSync(projectDir, dir, { recursive: true });
    rmSync(join(dir, "src", "Bad.ts"));
    mkdirSync(join(dir, ".abfc", "stubs", "test", "Script"), { recursive: true });
    writeFileSync(join(dir, ".abfc", "stubs", "test", "Script", "FakeWorld.d.ts"), GAME_STUB, "utf8");
    writeFileSync(join(dir, "src", "Flags.ts"), source(body, members), "utf8");
    const loaded = loadProgram(dir);
    assert.deepEqual(loaded.diagnostics.map((d) => `${d.code} ${d.message}`), []);
    const sf = loaded.files.classes.find((f) => f.fileName.endsWith("/Flags.ts"));
    assert.ok(sf);
    return buildHir(loaded, config, profile, [sf]);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function irOf(body: string, members = ""): IrModule {
  const hir = hirOf(body, members);
  assert.deepEqual(hir.diagnostics.map((d) => `${d.code} ${d.message}`), []);
  const ir = lower(hir, profile);
  assert.deepEqual(validateIrModule(ir), []);
  return ir;
}

const goUnit = (ir: IrModule): IrUnit => {
  const u = ir.assets[0]!.units.find((x) => x.id === "event:Go");
  assert.ok(u);
  return u;
};
const calls = (u: IrUnit, fn: string): IrNode[] => u.nodes.filter((n) => n.sem?.k === "call" && n.sem.function === fn);
const into = (u: IrUnit, to: string): string[] => u.wires.filter((w) => w[1] === to).map((w) => w[0]);
const SUBSYS = "/Script/BlueprintGraph.K2Node_GetSubsystem";

test("getWorldSubsystem: one pure Get Subsystem node with the class as CustomClass, wired into the subsystem calls", () => {
  const u = goUnit(irOf(`    const flags = getWorldSubsystem(FakeFlagSubsystem);
    const has = flags.HasWorldFlag({ RowName: "Flag_Test" });
    if (!has) {
      flags.SetWorldFlag({ RowName: "Flag_Test" }, true, this);
    }
    this.Seen = flags.HasWorldFlag({ RowName: "Flag_Test" });`));
  const subs = u.nodes.filter((n) => n.t3d.class === SUBSYS);
  assert.ok(subs.length >= 1);
  for (const s of subs) {
    assert.deepEqual(s.t3d.props, [`CustomClass="/Script/CoreUObject.Class'/Script/FakeWorld.FakeFlagSubsystem'"`]);
    assert.equal(s.sem, undefined, "a plain node: the backend writes it from class + props");
    assert.equal(into(u, `${s.id}.execute`).length, 0, "pure: no exec in");
  }
  const has = calls(u, "HasWorldFlag");
  const set = calls(u, "SetWorldFlag");
  assert.equal(has.length, 2);
  assert.equal(set.length, 1);
  for (const n of [...has, ...set]) {
    const self = into(u, `${n.id}.self`);
    assert.equal(self.length, 1);
    assert.ok(subs.some((s) => self[0] === `${s.id}.ReturnValue`), "the target is the Get Subsystem output");
    assert.equal(n.pinDefaults?.WorldFlag, `(RowName=\\"Flag_Test\\")`, "a row literal is the pin default (quotes escaped for DefaultValue=\"...\"), no Make node");
  }
  assert.equal(set[0]!.pinDefaults?.bState, "true");
  assert.ok(!u.nodes.some((n) => n.t3d.class === profile.nodeClasses.makeStruct), "no Make FakeFlagRowHandle");
});

test("getWorldSubsystem: a row from a name goes through Conv_NameToFakeFlag", () => {
  const u = goUnit(irOf(`    getWorldSubsystem(FakeFlagSubsystem).SetWorldFlag(FakeWorldLibrary.Conv_NameToFakeFlag(this.Row), true, this);`));
  const set = calls(u, "SetWorldFlag")[0]!;
  const conv = calls(u, "Conv_NameToFakeFlag")[0]!;
  assert.deepEqual(into(u, `${set.id}.WorldFlag`), [`${conv.id}.ReturnValue`]);
  assert.equal(set.pinDefaults?.WorldFlag, undefined);
});

test("a row literal held in a const is still a pin default", () => {
  const u = goUnit(irOf(`    const row: FakeFlagRowHandle = { RowName: nameOf("Flag_Const") };
    this.Seen = getWorldSubsystem(FakeFlagSubsystem).HasWorldFlag(row);`));
  assert.equal(calls(u, "HasWorldFlag")[0]!.pinDefaults?.WorldFlag, `(RowName=\\"Flag_Const\\")`);
});

test("a row handle built from a variable is refused (no Make node exists for it)", () => {
  const hir = hirOf(`    this.Seen = getWorldSubsystem(FakeFlagSubsystem).HasWorldFlag({ RowName: this.Row });`);
  assert.deepEqual(hir.diagnostics, []);
  assert.throws(() => lower(hir, profile), /FakeFlagRowHandle built from values.*Conv_NameTo/);
});

test("getWorldSubsystem refuses a class that is not a native subsystem", () => {
  const own = hirOf(`    const a = getWorldSubsystem(BP_Flags);
    this.Seen = isValid(a);`);
  assert.ok(own.diagnostics.some((d) => d.code === "ABFC2099" && /native subsystem class/.test(d.message)), JSON.stringify(own.diagnostics));
});
